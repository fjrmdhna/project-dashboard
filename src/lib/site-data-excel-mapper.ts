import { normalizeSystemKey } from '@/lib/supabase-site-sync'
import {
  excelDateToISO,
  numberOrNull,
  stringOrNull,
  type ExcelRow,
} from '@/lib/upload-gateway-utils'

/** Mapper for legacy site_data (swap) uploads. */
export function mapSiteDataExcelRow(row: ExcelRow): Record<string, unknown> | null {
  const systemKey = normalizeSystemKey(row.system_key)
  if (!systemKey) return null

  return {
    system_key: systemKey,
    site_id: stringOrNull(row.site_id),
    site_name: stringOrNull(row.site_name),
    mc_cluster: stringOrNull(row.mc_cluster),
    dati_ii: stringOrNull(row.dati_ii),
    scope_of_work: stringOrNull(row.scope_of_work),
    ran_scope: stringOrNull(row.ran_scope),
    latitude: numberOrNull(row.lat),
    longitude: numberOrNull(row.long),
    nano_cluster: stringOrNull(row.nano_cluster),
    site_status: stringOrNull(row.site_status),
    site_blocking: stringOrNull(row.site_blocking),
    sales_area: stringOrNull(row.sales_area),
    year: stringOrNull(row.year),
    swap_weekly_plan: stringOrNull(row.swap_weekly_plan),
    swap_monthly_plan: stringOrNull(row.swap_monthly_plan),
    swap_time_sec1_ff: stringOrNull(row.swap_time_sec1_ff),
    swap_time_sec2_ff: stringOrNull(row.swap_time_sec2_ff),
    swap_time_sec3_ff: stringOrNull(row.swap_time_sec3_ff),
    swap_time_sec1_af: stringOrNull(row.swap_time_sec1_af),
    swap_time_sec2_af: stringOrNull(row.swap_time_sec2_af),
    swap_time_sec3_af: stringOrNull(row.swap_time_sec3_af),
    area: stringOrNull(row.area),
    scope_strategy: stringOrNull(row.scope_strategy),
    wbs_status: stringOrNull(row.wbs_status),
    site_program: stringOrNull(row.site_program),
    remarks: stringOrNull(row.remarks),
    survey_ff: excelDateToISO(row.survey_ff),
    hybrid_optimization_af: excelDateToISO(row.hybrid_optimization_af),
    survey_af: excelDateToISO(row.survey_af),
    mos_ff: excelDateToISO(row.mos_ff),
    mos_bf: excelDateToISO(row.mos_bf),
    mos_af: excelDateToISO(row.mos_af),
    cutover_ff: excelDateToISO(row.cutover_ff),
    cutover_bf: excelDateToISO(row.cutover_bf),
    cutover_af: excelDateToISO(row.cutover_af),
    site_dismantle_ff: excelDateToISO(row.site_dismantle_ff),
    site_dismantle_bf: excelDateToISO(row.site_dismantle_bf),
    site_dismantle_af: excelDateToISO(row.site_dismantle_af),
    cx_approved: excelDateToISO(row.cx_approved),
    hotnews_af: excelDateToISO(row.hotnews_af),
    rfs_af: excelDateToISO(row.rfs_af),
    ready_for_acpt_date: excelDateToISO(row.ready_for_acpt_date),
    rfc_submitted: excelDateToISO(row.rfc_submitted),
    rfc_approved: excelDateToISO(row.rfc_approved),
    endorse_af: excelDateToISO(row.endorse_af),
    pac_accepted_af: excelDateToISO(row.pac_accepted_af),
    cluster_acceptance_af: excelDateToISO(row.cluster_acceptance_af),
    patp_accepted_af: excelDateToISO(row.patp_accepted_af),
    mocn_activation_forecast: excelDateToISO(row.mocn_activation_forecast),
    fac_af: excelDateToISO(row.fac_af),
    '5g_activation_date': excelDateToISO(row['5g_activation_date']),
    '5g_readiness_date': excelDateToISO(row['5g_readiness_date']),
  }
}
